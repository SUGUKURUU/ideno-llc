export function getPortfolioCaseById(id: string): PortfolioCase | undefined {
  return portfolioCases.find(c => c.id === id);
}

export function getPortfolioCasesByCategory(categoryId: string): PortfolioCase[] {
  return portfolioCases.filter(c => c.categoryId === categoryId);
}

export function getAllPortfolioCaseIds(): string[] {
  return portfolioCases.map(c => c.id);
}

export function getRelatedCases(caseId: string, limit: number = 3): PortfolioCase[] {
  const currentCase = getPortfolioCaseById(caseId);
  if (!currentCase) return [];

  const related = portfolioCases.filter(
    c => currentCase.relatedCaseIds.includes(c.id)
  );

  return related.slice(0, limit);
}
